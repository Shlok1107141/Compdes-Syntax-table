/*
 * symtab_target.h -- Arduino Uno settings for the engine copy in this folder.
 * symtab_common.h includes this file when it sits next to it; engine/ has no
 * such file, so host builds are unaffected.
 *
 * One structure per firmware build (the Uno cannot hold eight sets of arenas):
 *   BENCH_VARIANT 0 baseline, 1 A, 2 B, 3 C, 4 AB, 5 AC, 6 BC, 7 ABC
 * Change it here in the Arduino IDE, or pass -DBENCH_VARIANT=n (collect.py does).
 */
#ifndef SYMTAB_TARGET_H
#define SYMTAB_TARGET_H

#ifndef BENCH_VARIANT
#define BENCH_VARIANT 7
#endif

#define SYMTAB_NO_MAIN              /* the variants' PC demo main() is not wanted here */

#include "pools.h"                  /* generated by firmware/tools/gen_workloads.py */

#if BENCH_VARIANT == 2
#define ARENA_MAX_NODES   POOL_B_NODES
#define ARENA_MAX_CHARS   POOL_B_CHARS
#elif BENCH_VARIANT == 4
#define ARENA_MAX_NODES   POOL_AB_NODES
#define ARENA_MAX_CHARS   POOL_AB_CHARS
#elif BENCH_VARIANT == 6
#define ARENA_MAX_NODES   POOL_BC_NODES
#define ARENA_MAX_CHARS   POOL_BC_CHARS
#define ARENA_MAX_META    POOL_BC_META
#define ARENA_MAX_SHADOWS POOL_BC_SHADOWS
#elif BENCH_VARIANT == 7
#define ARENA_MAX_NODES   POOL_ABC_NODES
#define ARENA_MAX_CHARS   POOL_ABC_CHARS
#define ARENA_MAX_META    POOL_ABC_META
#define ARENA_MAX_SHADOWS POOL_ABC_SHADOWS
#endif

/* Every variant source is compiled; the linker keeps only the selected one's
 * arrays. The others still need a size that fits a 16-bit address space. */
#define ARENA_MAX_ITEMS   1u
#ifndef ARENA_MAX_CHARS
#define ARENA_MAX_CHARS   1u
#endif

#ifdef __AVR__
/* avr-libc keeps one size_t (2 bytes) in front of each malloc block. The
 * benchmark checks this model against the real heap on every run. */
#define MALLOC_OVERHEAD   sizeof(size_t)

/* The variants' breakdown() reports are for the PC demos; on AVR their format
 * strings would be copied into RAM. The never-taken branch keeps the arguments
 * "used" for the compiler, which then drops the call and its strings. The
 * harness prints with printf_P (format strings stay in flash). */
#include <stdio.h>
#define printf(...)       ((void)(0 ? printf(__VA_ARGS__) : 0))
#endif

#endif
